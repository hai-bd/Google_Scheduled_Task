#!/usr/bin/env python3
"""
Exact-Time Daily Email Dispatcher (08:00 Asia/Shanghai)

Reads records/latest_dispatch.json generated by the 06:00 compute job:
  1. Verifies today's report exists; if missing and --fallback-compute is enabled,
     automatically triggers cloud/gold_daily_compute.py as a safety net.
  2. If --wait-until HH:MM is set (e.g. 08:00) and current Shanghai time is earlier
     (within max_wait_minutes), sleeps until the exact target second so the email
     lands right at 08:00:00 Beijing Time despite GitHub Actions cron jitter.
  3. Sends multipart (HTML + plain Markdown fallback) email via SMTP SSL (supports
     Gmail SMTP, QQ Mail SMTP, or custom SMTP server via environment variables).
"""

from __future__ import annotations

import argparse
import json
import os
import smtplib
import subprocess
import sys
import time
from datetime import datetime
from email.header import Header
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.utils import formataddr
from pathlib import Path
from zoneinfo import ZoneInfo

REPO_ROOT = Path(__file__).resolve().parent.parent
MODELS_CONFIG_PATH = REPO_ROOT / "config" / "models.json"
LATEST_DISPATCH_PATH = REPO_ROOT / "records" / "latest_dispatch.json"
COMPUTE_SCRIPT = REPO_ROOT / "cloud" / "gold_daily_compute.py"

SHANGHAI_TZ = ZoneInfo("Asia/Shanghai")
DOTENV_PATH = REPO_ROOT / ".env"


def load_local_dotenv() -> None:
    """Load simple KEY=VALUE lines from local .env if present (never overrides existing env)."""
    if not DOTENV_PATH.exists():
        return
    for raw_line in DOTENV_PATH.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        k = k.strip()
        v = v.strip().strip('"').strip("'")
        if k and k not in os.environ:
            os.environ[k] = v


def wait_until_target_time(target_hhmm: str, max_wait_minutes: int = 30) -> None:
    hour_s, minute_s = target_hhmm.split(":")
    now = datetime.now(SHANGHAI_TZ)
    target = now.replace(hour=int(hour_s), minute=int(minute_s), second=0, microsecond=0)
    delta_sec = (target - now).total_seconds()
    if 0 < delta_sec <= max_wait_minutes * 60:
        print(
            f"[INFO] Current CST={now.strftime('%H:%M:%S')}, sleeping {int(delta_sec)}s "
            f"until exact {target_hhmm}:00 CST..."
        )
        time.sleep(delta_sec)
    elif delta_sec > max_wait_minutes * 60:
        print(
            f"[INFO] Target {target_hhmm} is {int(delta_sec/60)}m away (> {max_wait_minutes}m cap); "
            "sending immediately."
        )
    else:
        print(f"[INFO] Current CST={now.strftime('%H:%M:%S')} already past {target_hhmm}; sending now.")


def parse_recipients(raw: str | list[str]) -> list[str]:
    if isinstance(raw, list):
        return [str(x).strip() for x in raw if str(x).strip()]
    return [x.strip() for x in str(raw).replace(";", ",").split(",") if x.strip()]


def send_smtp_email(
    *,
    smtp_host: str,
    smtp_port: int,
    smtp_user: str,
    smtp_pass: str,
    recipients: list[str],
    subject: str,
    text_body: str,
    html_body: str,
) -> None:
    msg = MIMEMultipart("alternative")
    msg["From"] = formataddr((str(Header("黄金投资多Agent投委会", "utf-8")), smtp_user))
    msg["To"] = ", ".join(recipients)
    msg["Subject"] = Header(subject, "utf-8")

    msg.attach(MIMEText(text_body, "plain", "utf-8"))
    msg.attach(MIMEText(html_body, "html", "utf-8"))

    if smtp_port == 465:
        with smtplib.SMTP_SSL(smtp_host, smtp_port, timeout=30) as server:
            server.login(smtp_user, smtp_pass)
            server.sendmail(smtp_user, recipients, msg.as_string())
    else:
        with smtplib.SMTP(smtp_host, smtp_port, timeout=30) as server:
            server.ehlo()
            server.starttls()
            server.login(smtp_user, smtp_pass)
            server.sendmail(smtp_user, recipients, msg.as_string())


def main() -> None:
    parser = argparse.ArgumentParser(description="Send pre-computed daily gold decision email")
    parser.add_argument("--wait-until", type=str, default=None, help="Target CST HH:MM (e.g. 08:00)")
    parser.add_argument("--no-wait", action="store_true", help="Send immediately without waiting")
    parser.add_argument("--force-resend", action="store_true", help="Send even if already marked sent")
    parser.add_argument("--to", type=str, default=None, help="Override recipient(s), comma-separated")
    parser.add_argument(
        "--fallback-compute",
        action="store_true",
        help="If today's report is missing, run gold_daily_compute.py automatically",
    )
    args = parser.parse_args()
    load_local_dotenv()

    today_str = datetime.now(SHANGHAI_TZ).strftime("%Y-%m-%d")

    with open(MODELS_CONFIG_PATH, "r", encoding="utf-8") as f:
        models_cfg = json.load(f)

    smtp_host = (os.environ.get("SMTP_HOST") or "").strip() or "smtp.gmail.com"
    smtp_port = int((os.environ.get("SMTP_PORT") or "").strip() or "465")
    smtp_user = (os.environ.get("SMTP_USER") or "").strip()
    smtp_pass = (os.environ.get("SMTP_PASSWORD") or "").strip()
    raw_recipients = (
        args.to
        or (os.environ.get("EMAIL_TO") or "").strip()
        or models_cfg["email"].get("recipients")
        or models_cfg["email"]["recipient"]
    )
    recipients = parse_recipients(raw_recipients)

    if not smtp_user or not smtp_pass:
        raise SystemExit("ERROR: SMTP_USER and SMTP_PASSWORD environment variables must be set.")

    dispatch: dict | None = None
    if LATEST_DISPATCH_PATH.exists():
        dispatch = json.loads(LATEST_DISPATCH_PATH.read_text(encoding="utf-8"))

    needs_compute = dispatch is None or dispatch.get("date") != today_str
    if needs_compute:
        if args.fallback_compute:
            print(f"[WARN] No report found for {today_str}; running fallback compute now...")
            proc = subprocess.run([sys.executable, str(COMPUTE_SCRIPT)], check=False)
            if proc.returncode == 0 and LATEST_DISPATCH_PATH.exists():
                dispatch = json.loads(LATEST_DISPATCH_PATH.read_text(encoding="utf-8"))
            else:
                # Send failure alert email so the user is never silently left without notice
                send_smtp_email(
                    smtp_host=smtp_host,
                    smtp_port=smtp_port,
                    smtp_user=smtp_user,
                    smtp_pass=smtp_pass,
                    recipients=recipients,
                    subject=f"【告警】黄金投委会 {today_str} 自动计算失败",
                    text_body=f"今日（{today_str}）06:00 定时计算及兜底重跑均失败，请登录 GitHub Actions 查看运行日志。",
                    html_body=(
                        f"<h3>黄金投委会 {today_str} 自动计算告警</h3>"
                        "<p>今日 06:00 定时计算及 08:00 兜底重跑均失败，请登录 GitHub Actions 查看日志并检查 GEMINI_API_KEY 额度或网络状态。</p>"
                    ),
                )
                raise SystemExit("ERROR: Fallback compute failed; alert email sent.")
        else:
            raise SystemExit(
                f"ERROR: No dispatch report for today ({today_str}). Run gold_daily_compute.py first "
                "or pass --fallback-compute."
            )

    if dispatch.get("sent") and not args.force_resend:
        print(f"[INFO] Report for {today_str} was already sent at {dispatch.get('sent_at_cst')}. Skipping.")
        return

    if args.wait_until and not args.no_wait:
        wait_until_target_time(args.wait_until)

    html_p = Path(dispatch["html_path"])
    text_p = Path(dispatch["text_path"])
    if not html_p.is_absolute():
        html_p = REPO_ROOT / html_p
    if not text_p.is_absolute():
        text_p = REPO_ROOT / text_p
    html_body = html_p.read_text(encoding="utf-8")
    text_body = text_p.read_text(encoding="utf-8")

    send_smtp_email(
        smtp_host=smtp_host,
        smtp_port=smtp_port,
        smtp_user=smtp_user,
        smtp_pass=smtp_pass,
        recipients=recipients,
        subject=dispatch["subject"],
        text_body=text_body,
        html_body=html_body,
    )

    if not args.to:
        dispatch["sent"] = True
        dispatch["sent_at_cst"] = datetime.now(SHANGHAI_TZ).isoformat()
        dispatch["recipients"] = recipients
        LATEST_DISPATCH_PATH.write_text(json.dumps(dispatch, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"[INFO] Email sent successfully to {', '.join(recipients)} at {datetime.now(SHANGHAI_TZ).isoformat()}!")


if __name__ == "__main__":
    main()
